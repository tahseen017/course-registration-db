#!/usr/bin/env python3
"""
run_analysis.py — execute all 20 queries in analysis_queries.sql against
registration.db and write query_results.md (question + SQL + result table).

Also applies views.sql first (so view-based checks work) and demonstrates
that the prerequisite trigger blocks an illegal registration.

Usage:  python run_analysis.py        (run from this folder, after seed_data.py)
"""
import os
import re
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, "registration.db")
QUERIES = os.path.join(HERE, "analysis_queries.sql")
VIEWS = os.path.join(HERE, "views.sql")
OUT = os.path.join(HERE, "query_results.md")

MARKER = re.compile(r"^-- QUERY (Q\d+) \| (.+)$")
TECH = re.compile(r"^-- techniques: (.+)$")


def parse_queries(path):
    blocks, cur = [], None
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            m = MARKER.match(stripped)
            t = TECH.match(stripped)
            if m:
                cur = {"id": m.group(1), "question": m.group(2).strip(),
                       "techniques": "", "sql": []}
                blocks.append(cur)
            elif t and cur is not None and not cur["techniques"]:
                cur["techniques"] = t.group(1).strip()
            elif cur is not None:
                cur["sql"].append(line.rstrip())
    for b in blocks:
        b["sql"] = "\n".join(b["sql"]).strip().rstrip(";")
    return blocks


def md_table(cols, rows, limit=25):
    def esc(v):
        return "NULL" if v is None else str(v).replace("|", "\\|")
    out = ["| " + " | ".join(cols) + " |",
           "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in rows[:limit]:
        out.append("| " + " | ".join(esc(v) for v in r) + " |")
    if len(rows) > limit:
        out.append(f"| … | *{len(rows) - limit} more rows* |" + " " * 0 + "|")
    return "\n".join(out)


def main():
    con = sqlite3.connect(DB)
    con.execute("PRAGMA foreign_keys = ON")
    cur = con.cursor()

    cur.execute("DROP VIEW IF EXISTS current_semester_transcript")
    cur.execute("DROP VIEW IF EXISTS department_performance")
    with open(VIEWS, encoding="utf-8") as f:
        cur.executescript(f.read())          # install the two views

    blocks = parse_queries(QUERIES)
    assert len(blocks) == 20, f"expected 20 queries, parsed {len(blocks)}"

    lines = ["# Query results — course-registration-db", "",
             "Auto-generated by `run_analysis.py` from `analysis_queries.sql` "
             "against `registration.db` (5,000 enrollments).", ""]

    for b in blocks:
        cur.execute(b["sql"])
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        lines += [f"## {b['id']} — {b['question']}", "",
                  f"*Techniques:* {b['techniques']}", "",
                  "```sql", b["sql"], "```", "",
                  f"**{len(rows)} rows**", "",
                  md_table(cols, rows), ""]

    # ---- trigger demonstration ------------------------------------------------
    lines += ["## Trigger demo — prerequisites are enforced", "",
              "Trying to register a student into a section of a course whose "
              "prerequisite they have NOT passed:", "", "```sql",
              "INSERT INTO enrollments(student_id, section_id, enrolled_date, "
              "grade_letter, grade_points) VALUES (2026155, 12, '2026-08-24', 'B', 3.0);",
              "```", ""]
    try:
        cur.execute("INSERT INTO enrollments(student_id, section_id, enrolled_date, "
                    "grade_letter, grade_points) VALUES (2026155, 12, '2026-08-24', 'B', 3.0)")
        lines += ["Result: **insert succeeded (unexpected!)**", ""]
    except sqlite3.IntegrityError as e:
        lines += [f"Result: **blocked by trigger `enforce_prerequisites`** → `{e}`", ""]

    # ---- view sanity checks -----------------------------------------------------
    cur.execute("SELECT COUNT(*) FROM current_semester_transcript")
    n_tr = cur.fetchone()[0]
    cur.execute("SELECT dept, students, avg_cgpa, pass_rate_pct FROM department_performance "
                "ORDER BY avg_cgpa DESC")
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()
    lines += ["## View check — `department_performance`", "",
              f"`current_semester_transcript` has {n_tr} rows (Fall 2026).", "",
              md_table(cols, rows), ""]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT} with {len(blocks)} query results + trigger demo + view check")
    con.close()


if __name__ == "__main__":
    main()
